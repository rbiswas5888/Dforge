"""
DF-UX Intelligence - Visual Generation Engine
Synthesizes structured, production-grade, editable DFIR designs from natural language prompts.
"""

from typing import Dict, Any, List
from ..models.dfir import (
    DFIRDocument, DFIRMetadata, DFIRTokens, DFIRNode, DFIRTransform,
    DFIRLayout, DFIRStyle, DFIRFill, DFIRStroke, DFIRShadow, DFIRText,
    DFIRUXRationale, generate_node_id
)
from ..orchestration.planner import TaskPlanner


class VisualGenerationEngine:
    @classmethod
    def generate(cls, prompt: str, options: Dict[str, Any] = None) -> DFIRDocument:
        plan = TaskPlanner.create_plan(prompt, options)
        domain = plan["domain"]
        platform = plan["platform"]
        viewport = plan["viewport"]
        tokens_map = plan["recommended_tokens"]

        # 1. Base Document Structure
        metadata = DFIRMetadata(
            title=f"{domain.capitalize()} {platform.capitalize()} Interface",
            description=f"Generated by DF-UX Intelligence for prompt: '{prompt}'",
            domain=domain.capitalize(),
            industry=options.get("industry", "Technology") if options else "Technology",
            platform=platform,
            viewport=viewport,
            author="DF-UX Intelligence Native Engine"
        )

        tokens = DFIRTokens(
            colors={
                "brand_primary": tokens_map["brand"],
                "brand_accent": tokens_map["accent"],
                "bg_main": tokens_map["bg"],
                "bg_surface": tokens_map["surface"],
                "text_primary": tokens_map["text"],
                "text_muted": "#94A3B8",
                "border_subtle": "#334155",
                "status_success": "#10B981"
            },
            spacing={"xs": 4, "sm": 8, "md": 16, "lg": 24, "xl": 32},
            radii={"sm": 6, "md": 10, "lg": 16, "full": 9999}
        )

        # 2. Synthesize Native Root Artboard
        root_width = float(viewport["width"])
        root_height = float(viewport["height"])

        root = DFIRNode(
            id=generate_node_id("frame_artboard"),
            type="frame",
            name=f"{metadata.title} ({int(root_width)}px)",
            transform=DFIRTransform(x=0, y=0, width=root_width, height=root_height),
            layout=DFIRLayout(
                mode="stack-horizontal" if platform == "desktop" else "stack-vertical",
                alignItems="stretch"
            ),
            style=DFIRStyle(
                fills=[DFIRFill(type="solid", color=tokens_map["bg"])],
                cornerRadius=12 if platform == "mobile" else 0
            ),
            accessibility={"semanticTag": "main", "role": "main"}
        )

        # 3. Build Domain Specific Component Tree
        if platform == "desktop":
            cls._build_desktop_shell(root, domain, tokens_map, root_width, root_height, prompt)
        else:
            cls._build_mobile_shell(root, domain, tokens_map, root_width, root_height, prompt)

        # 4. UX Rationale & Heuristics applied
        ux_rationale = DFIRUXRationale(
            userGoals=[
                "Scan key status metrics rapidly",
                "Complete primary workflow actions with minimum cognitive friction",
                "Maintain continuous orientation via persistent navigation"
            ],
            informationArchitecture=plan["ia_strategy"],
            heuristicsApplied=plan["heuristics"],
            accessibilityNotes="All text-to-background contrast ratios strictly meet WCAG 2.2 AA standards (minimum 4.5:1 ratio).",
            designSystemRationale=f"Adheres to {domain} industry standards using unified 8pt grid spacing and tokenized color hierarchies."
        )

        return DFIRDocument(
            metadata=metadata,
            tokens=tokens,
            root=root,
            uxRationale=ux_rationale
        )

    @classmethod
    def _build_desktop_shell(cls, root: DFIRNode, domain: str, tokens: Dict[str, str], w: float, h: float, prompt: str):
        sidebar_w = 250.0

        # Sidebar Navigation
        sidebar = DFIRNode(
            id=generate_node_id("sidebar"),
            type="frame",
            name="Sidebar Navigation",
            transform=DFIRTransform(x=0, y=0, width=sidebar_w, height=h),
            layout=DFIRLayout(
                mode="stack-vertical",
                paddingTop=24,
                paddingBottom=24,
                paddingLeft=20,
                paddingRight=20,
                gap=16
            ),
            style=DFIRStyle(
                fills=[DFIRFill(type="solid", color="#0B132B")],
                strokes=[DFIRStroke(color="#1E293B", width=1, align="inside")]
            ),
            accessibility={"semanticTag": "nav", "role": "navigation"}
        )

        # Brand / Logo in Sidebar
        logo = DFIRNode(
            id=generate_node_id("logo"),
            type="text",
            name="App Logo",
            transform=DFIRTransform(width=sidebar_w - 40, height=28),
            text=DFIRText(
                content=f"⚡ {domain.upper()} FORGE",
                fontSize=16,
                fontWeight="800",
                color=tokens["brand"]
            )
        )
        sidebar.children.append(logo)

        # Nav Items
        nav_items = ["📊 Overview", "💳 Transactions", "📈 Analytics", "👥 Customers", "⚙️ Settings"]
        for idx, item in enumerate(nav_items):
            is_active = (idx == 0)
            nav_btn = DFIRNode(
                id=generate_node_id("nav_item"),
                type="frame",
                name=f"Nav Item / {item.split(' ')[1]}",
                transform=DFIRTransform(width=sidebar_w - 40, height=38),
                layout=DFIRLayout(mode="stack-horizontal", alignItems="center", paddingLeft=12, paddingRight=12),
                style=DFIRStyle(
                    fills=[DFIRFill(type="solid", color=tokens["surface"])] if is_active else [],
                    cornerRadius=8
                ),
                children=[
                    DFIRNode(
                        id=generate_node_id("nav_txt"),
                        type="text",
                        name="Nav Label",
                        transform=DFIRTransform(width=160, height=18),
                        text=DFIRText(
                            content=item,
                            fontSize=13,
                            fontWeight="600" if is_active else "500",
                            color="#FFFFFF" if is_active else "#94A3B8"
                        )
                    )
                ]
            )
            sidebar.children.append(nav_btn)

        # Main Content Area
        content_w = w - sidebar_w
        main_content = DFIRNode(
            id=generate_node_id("main_content"),
            type="frame",
            name="Main Content Workspace",
            transform=DFIRTransform(x=sidebar_w, y=0, width=content_w, height=h),
            layout=DFIRLayout(
                mode="stack-vertical",
                paddingTop=32,
                paddingBottom=32,
                paddingLeft=36,
                paddingRight=36,
                gap=24,
                sizingHorizontal="fill"
            ),
            style=DFIRStyle(fills=[]),
            accessibility={"semanticTag": "section"}
        )

        # Header Title Bar
        header = DFIRNode(
            id=generate_node_id("header"),
            type="frame",
            name="Dashboard Header",
            transform=DFIRTransform(width=content_w - 72, height=44),
            layout=DFIRLayout(mode="stack-horizontal", justifyContent="space-between", alignItems="center"),
            style=DFIRStyle(fills=[]),
            children=[
                DFIRNode(
                    id=generate_node_id("header_title"),
                    type="text",
                    name="Screen Title",
                    transform=DFIRTransform(width=400, height=32),
                    text=DFIRText(content=f"{domain.capitalize()} Command Center", fontSize=22, fontWeight="700", color="#F8FAFC")
                ),
                DFIRNode(
                    id=generate_node_id("header_action_btn"),
                    type="frame",
                    name="Primary Action Button",
                    transform=DFIRTransform(width=140, height=38),
                    layout=DFIRLayout(mode="stack-horizontal", alignItems="center", justifyContent="center"),
                    style=DFIRStyle(fills=[DFIRFill(type="solid", color=tokens["brand"])], cornerRadius=8),
                    children=[
                        DFIRNode(
                            id=generate_node_id("btn_txt"),
                            type="text",
                            name="Btn Label",
                            transform=DFIRTransform(width=100, height=18),
                            text=DFIRText(content="+ New Action", fontSize=13, fontWeight="600", color="#FFFFFF", textAlign="center")
                        )
                    ]
                )
            ]
        )
        main_content.children.append(header)

        # KPI Row
        kpi_row = DFIRNode(
            id=generate_node_id("kpi_row"),
            type="frame",
            name="Metrics KPI Row",
            transform=DFIRTransform(width=content_w - 72, height=120),
            layout=DFIRLayout(mode="stack-horizontal", gap=20, sizingHorizontal="fill"),
            style=DFIRStyle(fills=[])
        )

        kpis = [
            {"label": "Total Portfolio Value", "value": "$1,489,200.50", "change": "+14.2% ↑", "positive": True},
            {"label": "Active Transactions", "value": "24,891", "change": "+5.8% ↑", "positive": True},
            {"label": "System Efficiency Rate", "value": "99.98%", "change": "Optimal", "positive": True}
        ]

        card_w = (content_w - 72 - 40) / 3
        for k in kpis:
            card = DFIRNode(
                id=generate_node_id("kpi_card"),
                type="frame",
                name=f"Card / {k['label']}",
                transform=DFIRTransform(width=card_w, height=120),
                layout=DFIRLayout(mode="stack-vertical", paddingTop=18, paddingLeft=20, paddingRight=20, paddingBottom=18, gap=6),
                style=DFIRStyle(
                    fills=[DFIRFill(type="solid", color=tokens["surface"])],
                    strokes=[DFIRStroke(color="#334155", width=1, align="inside")],
                    cornerRadius=10,
                    shadows=[DFIRShadow(y=6, blur=16, color="rgba(0,0,0,0.3)")]
                ),
                children=[
                    DFIRNode(
                        id=generate_node_id("kpi_lbl"),
                        type="text",
                        name="KPI Label",
                        transform=DFIRTransform(width=card_w - 40, height=16),
                        text=DFIRText(content=k["label"], fontSize=12, fontWeight="500", color="#94A3B8")
                    ),
                    DFIRNode(
                        id=generate_node_id("kpi_val"),
                        type="text",
                        name="KPI Value",
                        transform=DFIRTransform(width=card_w - 40, height=32),
                        text=DFIRText(content=k["value"], fontSize=24, fontWeight="800", color="#FFFFFF")
                    ),
                    DFIRNode(
                        id=generate_node_id("kpi_chg"),
                        type="text",
                        name="KPI Change",
                        transform=DFIRTransform(width=card_w - 40, height=16),
                        text=DFIRText(content=k["change"], fontSize=11, fontWeight="600", color=tokens["accent"])
                    )
                ]
            )
            kpi_row.children.append(card)

        main_content.children.append(kpi_row)

        # Data Table / Activity Feed Panel
        table_card = DFIRNode(
            id=generate_node_id("table_panel"),
            type="frame",
            name="Recent Transactions & Records Table",
            transform=DFIRTransform(width=content_w - 72, height=380),
            layout=DFIRLayout(mode="stack-vertical", paddingTop=20, paddingLeft=24, paddingRight=24, paddingBottom=20, gap=14, sizingHorizontal="fill"),
            style=DFIRStyle(
                fills=[DFIRFill(type="solid", color=tokens["surface"])],
                strokes=[DFIRStroke(color="#334155", width=1, align="inside")],
                cornerRadius=12
            ),
            children=[
                DFIRNode(
                    id=generate_node_id("tbl_title"),
                    type="text",
                    name="Table Title",
                    transform=DFIRTransform(width=400, height=22),
                    text=DFIRText(content="Live Activity & Data Stream", fontSize=15, fontWeight="700", color="#F8FAFC")
                )
            ]
        )

        # Table Rows
        rows = [
            {"id": "TX-9901", "name": "Global Asset Transfer", "date": "Today, 10:45 AM", "amount": "+$18,450.00", "status": "Completed"},
            {"id": "TX-9902", "name": "Cloud Infrastructure Settlement", "date": "Today, 09:12 AM", "amount": "-$4,210.80", "status": "Completed"},
            {"id": "TX-9903", "name": "API Service Subscription", "date": "Yesterday, 18:30 PM", "amount": "-$299.00", "status": "Completed"}
        ]

        for r in rows:
            row_frame = DFIRNode(
                id=generate_node_id("row"),
                type="frame",
                name=f"Row / {r['id']}",
                transform=DFIRTransform(width=content_w - 120, height=44),
                layout=DFIRLayout(mode="stack-horizontal", justifyContent="space-between", alignItems="center", paddingLeft=12, paddingRight=12),
                style=DFIRStyle(
                    fills=[DFIRFill(type="solid", color="#0F172A")],
                    cornerRadius=6
                ),
                children=[
                    DFIRNode(
                        id=generate_node_id("cell_title"),
                        type="text",
                        name="Cell Title",
                        transform=DFIRTransform(width=280, height=20),
                        text=DFIRText(content=f"{r['id']} — {r['name']}", fontSize=13, fontWeight="600", color="#F8FAFC")
                    ),
                    DFIRNode(
                        id=generate_node_id("cell_date"),
                        type="text",
                        name="Cell Date",
                        transform=DFIRTransform(width=160, height=18),
                        text=DFIRText(content=r["date"], fontSize=12, fontWeight="400", color="#94A3B8")
                    ),
                    DFIRNode(
                        id=generate_node_id("cell_amt"),
                        type="text",
                        name="Cell Amount",
                        transform=DFIRTransform(width=120, height=20),
                        text=DFIRText(content=r["amount"], fontSize=13, fontWeight="700", color="#38BDF8" if "+" in r["amount"] else "#F8FAFC", textAlign="right")
                    )
                ]
            )
            table_card.children.append(row_frame)

        main_content.children.append(table_card)

        # Assemble Root
        root.children.append(sidebar)
        root.children.append(main_content)

