        root.layout.paddingTop = 20
        root.layout.paddingLeft = 20
        root.layout.paddingRight = 20
        root.layout.paddingBottom = 20
        root.layout.gap = 16

        # Mobile Top Bar
        top_bar = DFIRNode(
            id=generate_node_id("mob_topbar"),
            type="frame",
            name="Mobile Header Bar",
            transform=DFIRTransform(width=w - 40, height=40),
            layout=DFIRLayout(mode="stack-horizontal", justifyContent="space-between", alignItems="center"),
            style=DFIRStyle(fills=[]),
            children=[
                DFIRNode(
                    id=generate_node_id("mob_title"),
                    type="text",
                    name="Header Label",
                    transform=DFIRTransform(width=220, height=26),
                    text=DFIRText(content=f"⚡ {domain.capitalize()} Mobile", fontSize=18, fontWeight="800", color="#FFFFFF")
                )
            ]
        )
        root.children.append(top_bar)

        # Primary Mobile Card
        card = DFIRNode(
            id=generate_node_id("mob_primary_card"),
            type="frame",
            name="Primary Focus Card",
            transform=DFIRTransform(width=w - 40, height=160),
            layout=DFIRLayout(mode="stack-vertical", paddingTop=20, paddingLeft=20, paddingRight=20, paddingBottom=20, gap=8),
            style=DFIRStyle(
                fills=[DFIRFill(type="solid", color=tokens["brand"])],
                cornerRadius=16,
                shadows=[DFIRShadow(y=8, blur=24, color="rgba(37,99,235,0.4)")]
            ),
            children=[
                DFIRNode(
                    id=generate_node_id("lbl"),
                    type="text",
                    name="Card Subtitle",
                    transform=DFIRTransform(width=w - 80, height=16),
                    text=DFIRText(content="Current Available Balance", fontSize=13, fontWeight="500", color="#BFDBFE")
                ),
                DFIRNode(
                    id=generate_node_id("val"),
                    type="text",
                    name="Card Value",
                    transform=DFIRTransform(width=w - 80, height=36),
                    text=DFIRText(content="$84,920.40", fontSize=28, fontWeight="800", color="#FFFFFF")
                )
            ]
        )
        root.children.append(card)

        # Action Buttons Row
        actions = DFIRNode(
            id=generate_node_id("mob_actions"),
            type="frame",
            name="Quick Actions Row",
            transform=DFIRTransform(width=w - 40, height=48),
            layout=DFIRLayout(mode="stack-horizontal", gap=12, sizingHorizontal="fill"),
            style=DFIRStyle(fills=[]),
            children=[
                DFIRNode(
                    id=generate_node_id("btn1"),
                    type="frame",
                    name="Action 1",
                    transform=DFIRTransform(width=(w - 52) / 2, height=48),
                    layout=DFIRLayout(mode="stack-horizontal", alignItems="center", justifyContent="center"),
                    style=DFIRStyle(fills=[DFIRFill(type="solid", color=tokens["surface"])], cornerRadius=10),
                    children=[
                        DFIRNode(
                            id=generate_node_id("btn1_txt"),
                            type="text",
                            name="Label",
                            transform=DFIRTransform(width=100, height=18),
                            text=DFIRText(content="↑ Send Funds", fontSize=13, fontWeight="600", color="#FFFFFF", textAlign="center")
                        )
                    ]
                ),
                DFIRNode(
                    id=generate_node_id("btn2"),
                    type="frame",
                    name="Action 2",
                    transform=DFIRTransform(width=(w - 52) / 2, height=48),
                    layout=DFIRLayout(mode="stack-horizontal", alignItems="center", justifyContent="center"),
                    style=DFIRStyle(fills=[DFIRFill(type="solid", color=tokens["surface"])], cornerRadius=10),
                    children=[
                        DFIRNode(
                            id=generate_node_id("btn2_txt"),
                            type="text",
                            name="Label",
                            transform=DFIRTransform(width=100, height=18),
                            text=DFIRText(content="↓ Receive", fontSize=13, fontWeight="600", color="#FFFFFF", textAlign="center")
                        )
                    ]
                )
            ]
        )
        root.children.append(actions)
