/**
 * DesignForge AI - Git & Repository Handoff Connector MCP Server
 */

import { McpServer } from '../server/server.js';
import { MCP_PERMISSIONS, TOOL_CATEGORIES } from '../protocol/types.js';

export class GitHandoffMcpServer extends McpServer {
  constructor(repoPath = '.') {
    super({
      name: 'designforge-git',
      version: '1.0.0',
      description: 'Repository inspection, code diff, and controlled handoff connector'
    });

    this.repoPath = repoPath;
    this.stagedFiles = new Map();
    this.commits = [
      { id: 'c1a8f90', message: 'feat: initialize design system and designforge compiler', date: new Date().toISOString() }
    ];

    this.registerGitTools();
  }

  registerGitTools() {
    this.registerTool({
      name: 'git_status',
      category: TOOL_CATEGORIES.REPOSITORY,
      description: 'Inspects repository status and exported React files ready for review.',
      inputSchema: { type: 'object', properties: {} },
      requiredScope: MCP_PERMISSIONS.REPOSITORY_READ
    }, async () => {
      return {
        branch: 'main',
        clean: this.stagedFiles.size === 0,
        stagedCount: this.stagedFiles.size,
        stagedFiles: Array.from(this.stagedFiles.keys()),
        recentCommits: this.commits.slice(0, 3)
      };
    });

    this.registerTool({
      name: 'git_diff',
      category: TOOL_CATEGORIES.REPOSITORY,
      description: 'Inspects code diff between current design state and exported files.',
      inputSchema: {
        type: 'object',
        properties: {
          filePath: { type: 'string' }
        }
      },
      requiredScope: MCP_PERMISSIONS.REPOSITORY_READ
    }, async (args) => {
      return {
        target: args.filePath || 'all-staged',
        diff: `diff --git a/src/App.tsx b/src/App.tsx
+ // Generated by DesignForge AI React Compiler
+ import React from 'react';
+ export default function App() { return <div className="min-h-screen bg-slate-900 text-white">...</div>; }`
      };
    });

    this.registerTool({
      name: 'git_commit',
      category: TOOL_CATEGORIES.REPOSITORY,
      description: 'Stages and commits exported React components to the project repository.',
      inputSchema: {
        type: 'object',
        properties: {
          message: { type: 'string', required: true }
        },
        required: ['message']
      },
      requiredScope: MCP_PERMISSIONS.REPOSITORY_WRITE,
      requiresApproval: true
    }, async (args) => {
      const commit = {
        id: Math.random().toString(16).slice(2, 9),
        message: args.message,
        date: new Date().toISOString()
      };
      this.commits.unshift(commit);
      this.stagedFiles.clear();
      return {
        success: true,
        commitId: commit.id,
        message: commit.message
      };
    });
  }
}
